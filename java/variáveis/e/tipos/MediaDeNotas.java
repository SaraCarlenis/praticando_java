package br.com.praticando.java.variáveis.e.tipos;

public class MediaDeNotas {
    public static void main(String[] args) {
        double nota1 = 7.5;
        double nota2 = 8.0;
        double nota3 = 9.0;

        double mediaNotas = (nota1 + nota2 + nota3) / 3;

        System.out.println("A media das notas é: " + mediaNotas);
    }
}
